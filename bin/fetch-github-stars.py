#!/usr/bin/env python3
"""Bake GitHub star counts into _data/github_stars.yml.

Scans _bibliography/papers.bib for `code` URLs and any `stars_also` repositories,
queries the GitHub API once per repository, and writes the counts to a data file
that the bib layout renders statically. Visitors then make no API calls at all.

    python3 bin/fetch-github-stars.py            # refresh
    GITHUB_TOKEN=ghp_... python3 bin/...         # 5000/hr instead of 60/hr

Run it before a build (or in CI) whenever the numbers should be refreshed.
Existing values are kept when a repository cannot be reached, so a rate limit
or a network blip never wipes the file.
"""

import json
import os
import re
import sys
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIB = os.path.join(ROOT, "_bibliography", "papers.bib")
OUT = os.path.join(ROOT, "_data", "github_stars.yml")


def repos_from_bib(text):
    """Every repo referenced by an active entry, in first-seen order."""
    text = re.sub(r"@comment\{.*?\n\}", "", text, flags=re.S)  # skip hidden entries
    found = []
    for m in re.finditer(r"code = \{https?://github\.com/([^}\s]+)\}", text):
        parts = m.group(1).strip("/").split("/")
        if len(parts) >= 2:
            found.append(f"{parts[0]}/{parts[1]}")
    for m in re.finditer(r"stars_also = \{([^}]*)\}", text):
        for r in m.group(1).split(","):
            r = r.strip().strip("/")
            if r:
                found.append(r)
    seen, out = set(), []
    for r in found:
        if r not in seen:
            seen.add(r)
            out.append(r)
    return out


def load_existing():
    if not os.path.exists(OUT):
        return {}
    data = {}
    with open(OUT, encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r'^\s*"?([^"#:\s]+)"?:\s*(\d+)\s*$', line)
            if m:
                data[m.group(1)] = int(m.group(2))
    return data


def fetch(repo, token):
    req = urllib.request.Request(
        f"https://api.github.com/repos/{repo}",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "al-folio-stars"},
    )
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.load(r).get("stargazers_count")


def main():
    with open(BIB, encoding="utf-8") as fh:
        repos = repos_from_bib(fh.read())
    token = os.environ.get("GITHUB_TOKEN")
    stars, failed = load_existing(), []

    for repo in repos:
        try:
            n = fetch(repo, token)
            if isinstance(n, int):
                stars[repo] = n
                print(f"  {repo:36s} {n}")
                continue
            failed.append(repo)
        except urllib.error.HTTPError as e:
            failed.append(f"{repo} (HTTP {e.code})")
        except Exception as e:                      # network, timeout, parse
            failed.append(f"{repo} ({type(e).__name__})")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# Generated by bin/fetch-github-stars.py -- do not edit by hand.\n")
        fh.write("# Re-run that script to refresh (set GITHUB_TOKEN to avoid rate limits).\n")
        for repo in sorted(stars):
            fh.write(f'"{repo}": {stars[repo]}\n')

    print(f"\nwrote {OUT} ({len(stars)} repos)")
    if failed:
        print("kept previous value for:", ", ".join(failed), file=sys.stderr)
        if not stars:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
